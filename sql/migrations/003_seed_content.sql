-- -------------------------------------------------------------
-- Привязка товаров к сериям и slug
-- -------------------------------------------------------------
UPDATE products p
INNER JOIN product_series ps ON ps.slug = 'eteo-one'
SET p.series_id = ps.id, p.slug = 'eteo-d1'
WHERE p.sku = 'ETEO-D1-BASE';

UPDATE products p
INNER JOIN product_series ps ON ps.slug = 'eteo-flow'
SET p.series_id = ps.id, p.slug = 'eteo-m3'
WHERE p.sku = 'ETEO-M3-BASE';

-- UNIQUE на slug (после заполнения)
SET @idx_exists = (
    SELECT COUNT(*) FROM INFORMATION_SCHEMA.STATISTICS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'products'
      AND INDEX_NAME = 'uq_products_slug'
);
SET @sql = IF(@idx_exists = 0,
    'ALTER TABLE products ADD UNIQUE KEY uq_products_slug (slug)',
    'SELECT ''uq_products_slug already exists'' AS info'
);
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

